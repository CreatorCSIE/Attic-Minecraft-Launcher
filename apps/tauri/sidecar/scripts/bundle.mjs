// sidecar 打包：esbuild 把 runtime 门面 + 全部 workspace 依赖压成单文件 CJS
// （发行形态 = src-tauri bundle.resources 里的 sidecar/server.cjs，由宿主 node 拉起）。
import { build } from 'esbuild';

await build({
  entryPoints: ['src/server.ts'],
  outfile: 'dist/server.cjs',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  // sidecar 只在 Tauri 线跑（Node 18+ 现代宿主）；Electron 22 兜底线不走本产物（那是同进程直连 runtime）。
  target: 'node18',
  banner: { js: '// generated by scripts/bundle.mjs — attic sidecar RPC server' },
});
console.log('[sidecar] bundled -> dist/server.cjs');
